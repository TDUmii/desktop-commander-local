import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:net';
import { createHash, randomBytes } from 'node:crypto';
import { startGateway } from '../scripts/local-web-gateway.mjs';

const temporary = await mkdtemp(join(tmpdir(), 'umibridge-oauth-restart-'));
const listener = createServer();
await new Promise(resolve => listener.listen(0, '127.0.0.1', resolve));
const port = listener.address().port;
await new Promise(resolve => listener.close(resolve));
const origin = `http://127.0.0.1:${port}`;
const secret = randomBytes(24).toString('base64url');
const settings = { port, publicUrl: origin, connectionSecret: secret, configDir: join(temporary, 'profile') };
const statePath = join(temporary, 'oauth-state.json');
const request = (path, options) => fetch(`${origin}${path}`, { redirect: 'manual', ...options });
const form = (path, data, headers = {}) => request(path, { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded', ...headers }, body: new URLSearchParams(data) });
const registration = { client_name: 'ChatGPT restart regression', redirect_uris: ['https://chatgpt.com/connector_platform/oauth/callback'], token_endpoint_auth_method: 'none', grant_types: ['authorization_code', 'refresh_token'], response_types: ['code'] };
let gateway;
try {
  gateway = await startGateway(settings);
  const registeredResponse = await request('/register', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(registration) });
  assert.equal(registeredResponse.status, 201);
  const registered = await registeredResponse.json();
  const verifier = randomBytes(32).toString('base64url');
  const params = { response_type: 'code', client_id: registered.client_id, redirect_uri: registration.redirect_uris[0], code_challenge: createHash('sha256').update(verifier).digest('base64url'), code_challenge_method: 'S256', resource: `${origin}/mcp`, scope: 'desktop' };
  const authorize = async () => {
    const response = await request(`/authorize?${new URLSearchParams(params)}`);
    assert.equal(response.status, 200);
    const cookie = response.headers.get('set-cookie').split(';')[0];
    const html = await response.text();
    const requestId = html.match(/name="requestId" value="([^"]+)"/)[1];
    const consent = await form('/consent', { requestId, secret }, { Cookie: cookie, Origin: origin });
    assert.equal(consent.status, 302);
    return new URL(consent.headers.get('location')).searchParams.get('code');
  };
  const exchangeCode = code => form('/token', { grant_type: 'authorization_code', client_id: registered.client_id, code, code_verifier: verifier, redirect_uri: registration.redirect_uris[0], resource: `${origin}/mcp` });
  const code = await authorize();
  const exchanged = await exchangeCode(code);
  assert.equal(exchanged.status, 200);
  const tokens = await exchanged.json();
  assert.equal(tokens.scope, 'desktop');
  assert.ok(tokens.refresh_token, 'ChatGPT requests refresh_token in DCR even when OAuth scope is desktop only.');
  assert.equal((await exchangeCode(code)).status, 400, 'Consumed codes cannot be replayed.');
  const unexchangedCode = await authorize();
  const pending = await request(`/authorize?${new URLSearchParams(params)}`);
  const pendingCookie = pending.headers.get('set-cookie').split(';')[0];
  const pendingId = (await pending.text()).match(/name="requestId" value="([^"]+)"/)[1];
  const snapshot = JSON.parse(await readFile(statePath, 'utf8'));
  assert.equal(snapshot.issuer, `${origin}/`);
  assert.deepEqual(Object.keys(snapshot).sort(), ['version', 'issuer', 'clients', 'access', 'refresh'].sort());
  assert.ok(snapshot.refresh[0][1].expiresAt - Date.now() > 29 * 24 * 60 * 60_000);
  assert.ok(!JSON.stringify(snapshot).includes(secret), 'The connection code is never included in OAuth state.');
  // Prove the former 24-hour registration expiry is gone without sleeping.
  snapshot.clients[0][1].client.client_id_issued_at -= 2 * 24 * 60 * 60;
  await gateway.close();
  await writeFile(statePath, JSON.stringify(snapshot));
  gateway = await startGateway(settings);
  assert.equal((await request('/mcp', { headers: { Authorization: `Bearer ${tokens.access_token}` } })).status, 405, 'Access grants survive a same-issuer restart.');
  assert.equal((await exchangeCode(unexchangedCode)).status, 400, 'Unexchanged codes must not survive restart.');
  assert.equal((await form('/consent', { requestId: pendingId, secret }, { Cookie: pendingCookie, Origin: origin })).status, 400, 'Consent requests must not survive restart.');
  const refreshForm = token => ({ grant_type: 'refresh_token', client_id: registered.client_id, refresh_token: token, resource: `${origin}/mcp` });
  const invalidScopes = await form('/token', { ...refreshForm(tokens.refresh_token), scope: 'desktop offline_access' });
  assert.equal(invalidScopes.status, 400);
  assert.equal((await invalidScopes.json()).error, 'invalid_scope');
  const refreshedResponse = await form('/token', refreshForm(tokens.refresh_token));
  assert.equal(refreshedResponse.status, 200);
  const refreshed = await refreshedResponse.json();
  assert.equal(refreshed.scope, 'desktop', 'A refresh preserves the exact granted scope.');
  assert.ok(refreshed.refresh_token, 'Rotation must keep returning a refresh token without offline_access.');
  assert.notEqual(refreshed.refresh_token, tokens.refresh_token);
  await gateway.close();
  gateway = await startGateway(settings);
  assert.equal((await request('/mcp', { headers: { Authorization: `Bearer ${tokens.access_token}` } })).status, 401, 'Rotated access revocation survives restart.');
  assert.equal((await form('/token', refreshForm(tokens.refresh_token))).status, 400, 'Rotated refresh tokens cannot return after restart.');
  assert.equal((await request('/mcp', { headers: { Authorization: `Bearer ${refreshed.access_token}` } })).status, 405);
  assert.equal((await form('/revoke', { client_id: registered.client_id, token: refreshed.refresh_token })).status, 200);
  await gateway.close();
  gateway = await startGateway(settings);
  assert.equal((await request('/mcp', { headers: { Authorization: `Bearer ${refreshed.access_token}` } })).status, 401, 'Revocation survives restart.');
  assert.equal((await form('/token', refreshForm(refreshed.refresh_token))).status, 400);
  const freshCode = await authorize();
  const freshTokens = await (await exchangeCode(freshCode)).json();
  await gateway.close();
  // Origin changes are expected with Quick Tunnel, but credentials must never cross issuers.
  gateway = await startGateway({ ...settings, publicUrl: `http://localhost:${port}` });
  assert.equal((await request('/mcp', { headers: { Authorization: `Bearer ${freshTokens.access_token}` } })).status, 401);
  assert.equal((await form('/token', refreshForm(freshTokens.refresh_token))).status, 400);
  const invalidClient = await request(`/authorize?${new URLSearchParams(params)}`);
  assert.equal(invalidClient.status, 400, 'A previous issuer\'s registration cannot be reused.');
  await gateway.close();
  await writeFile(statePath, '{"version":1,"issuer":');
  await assert.rejects(startGateway(settings), /Invalid local OAuth state/);
  console.log('PASS: desktop-only refresh, issuer-bound OAuth persistence, same-issuer restarts, code/consent expiry, scope preservation, rotation, revocation and corrupt-state fail-closed.');
} finally {
  await gateway?.close();
  await rm(temporary, { recursive: true, force: true });
}
