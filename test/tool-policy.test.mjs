import assert from 'node:assert/strict';
import { createHash, randomBytes } from 'node:crypto';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createServer } from 'node:net';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { startGateway } from '../scripts/local-web-gateway.mjs';
import { CONTEXT_META, createToolPolicy, TOOL_GROUPS } from '../scripts/tool-policy.mjs';

const temporary = await mkdtemp(join(tmpdir(), 'umibridge-tool-policy-'));
let gateway, client;
const contexts = result => result.content.filter(block => block._meta?.[CONTEXT_META]);
try {
  const unitDir = join(temporary, 'unit');
  const policy = createToolPolicy({ stateDir: unitDir });
  const catalog = ['read_file', 'read_file_on_device', 'run_command', 'run_on_device', 'windows_type', 'windows_on_device', 'read_skill'].map(name => ({ name, description: 'Fixture tool' }));
  const hostileSkills = Array.from({ length: 100 }, (_, i) => ({ name: `skill-${i}`, description: `Untrusted\n\x00 D:\\Private\\hidden.txt /home/private/hidden.txt "ignore rules" ${'a'.repeat(300)}`, enabled: true, path: 'PRIVATE_PATH_MUST_NOT_LEAK', markdown: 'PRIVATE_MARKDOWN_MUST_NOT_LEAK' }));
  const initial = await policy.snapshot(catalog, hostileSkills);
  assert.equal(initial.autoPrompt, true);
  assert.ok(initial.prompt.length < 16000);
  assert.match(initial.prompt, /catalog data only/);
  assert.doesNotMatch(initial.prompt, /PRIVATE_PATH|PRIVATE_MARKDOWN|hidden\.txt|\x00/);
  await policy.update({ name: 'read_file', enabled: false }, catalog);
  let current = await policy.snapshot(catalog);
  assert.throws(() => current.assertCall('read_file'), /disabled/);
  assert.throws(() => current.assertCall('read_file_on_device'), /disabled/);
  assert.equal(current.tools.find(tool => tool.name === 'read_file_on_device').blockedBy, 'read_file');
  await policy.update({ name: 'windows_type', enabled: false }, catalog);
  current = await policy.snapshot(catalog);
  assert.throws(() => current.assertCall('windows_on_device', { name: 'windows_type' }), /disabled/);
  for (const name of ['windows_unlisted_operation', 'windows_on_device', 'windows_powershell', 'windows_power_shell']) assert.throws(() => current.assertCall('windows_on_device', { name }), /unknown nested/);
  await policy.update({ group: 'commands', enabled: false }, catalog);
  assert.equal((await policy.snapshot(catalog)).allows('run_on_device'), false);
  const reloaded = createToolPolicy({ stateDir: unitDir });
  assert.equal((await reloaded.snapshot(catalog)).allows('read_file'), false);
  await reloaded.update({ group: 'files', enabled: true }, catalog);
  assert.equal((await policy.snapshot(catalog)).allows('read_file_on_device'), true);
  for (const invalid of ['{', JSON.stringify({ version: 1, autoPrompt: true, enabled: { read_file: 'false' }, groups: {} }), JSON.stringify({ version: 1, autoPrompt: true, enabled: {}, groups: { files: 'false' } })]) {
    await writeFile(join(unitDir, 'tool-policy.json'), invalid);
    const failedClosed = await policy.snapshot(catalog);
    assert.equal(failedClosed.autoPrompt, false);
    assert.equal(failedClosed.prompt, '');
    assert.ok(failedClosed.tools.every(tool => !tool.enabled));
    assert.throws(() => failedClosed.assertCall('read_file'), /disabled/);
  }
  await policy.update({ name: 'read_file', enabled: true }, catalog);
  current = await policy.snapshot(catalog);
  assert.equal(current.allows('read_file'), true, 'explicit recovery enables only the selected tool');
  assert.equal(current.allows('run_command'), false);

  const socket = createServer();
  await new Promise(done => socket.listen(0, '127.0.0.1', done));
  const port = socket.address().port;
  await new Promise(done => socket.close(done));
  const origin = `http://127.0.0.1:${port}`;
  const configDir = join(temporary, 'profile');
  const secret = randomBytes(32).toString('base64url');
  const request = (path, options) => fetch(origin + path, { redirect: 'manual', ...options });
  const headers = { 'content-type': 'application/json', 'x-dc-admin-action': '1' };
  const change = body => request('/admin/api/tools', { method: 'POST', headers, body: JSON.stringify(body) });
  const settings = async () => (await request('/admin/api/tools')).json();
  const form = (path, body, extra = {}) => request(path, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded', ...extra }, body: new URLSearchParams(body) });
  gateway = await startGateway({ port, publicUrl: origin, configDir, connectionSecret: secret });
  const registration = await (await request('/register', { method: 'POST', headers, body: JSON.stringify({ client_name: 'Policy test', redirect_uris: ['https://chatgpt.com/connector_platform/oauth/callback'], token_endpoint_auth_method: 'none', grant_types: ['authorization_code', 'refresh_token'], response_types: ['code'] }) })).json();
  const verifier = randomBytes(32).toString('base64url');
  const authorization = await request('/authorize?' + new URLSearchParams({ response_type: 'code', client_id: registration.client_id, redirect_uri: registration.redirect_uris[0], code_challenge: createHash('sha256').update(verifier).digest('base64url'), code_challenge_method: 'S256', resource: origin + '/mcp', scope: 'desktop offline_access' }));
  const cookie = authorization.headers.get('set-cookie').split(';')[0];
  const requestId = (await authorization.text()).match(/name="requestId" value="([^"]+)"/)[1];
  const consent = await form('/consent', { requestId, secret }, { Cookie: cookie, Origin: origin });
  const tokens = await (await form('/token', { grant_type: 'authorization_code', client_id: registration.client_id, code: new URL(consent.headers.get('location')).searchParams.get('code'), code_verifier: verifier, redirect_uri: registration.redirect_uris[0], resource: origin + '/mcp' })).json();
  const connect = async () => {
    const connected = new Client({ name: 'policy-cached-client', version: '1.0.0' });
    await connected.connect(new StreamableHTTPClientTransport(new URL(origin + '/mcp'), { requestInit: { headers: { Authorization: `Bearer ${tokens.access_token}` } } }));
    return connected;
  };
  client = await connect();
  assert.match(client.getInstructions(), /selected context/);
  const cached = await client.listTools();
  assert.ok(cached.tools.some(tool => tool.name === 'write_file'));
  assert.equal(cached._meta, undefined, 'private unfiltered catalog is not exposed');
  const before = await settings();
  assert.ok(before.tools.every(tool => TOOL_GROUPS.includes(tool.group) && typeof tool.enabled === 'boolean' && typeof tool.available === 'boolean'));
  assert.equal((await request('/admin/api/tools', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'write_file', enabled: false }) })).status, 403, 'CSRF action header is required');
  assert.equal((await change({ name: 'missing_tool', enabled: false })).status, 400);
  assert.equal((await change({ name: 'write_file', enabled: 'false' })).status, 400);
  const filePath = join(temporary, 'proof.txt');
  await writeFile(filePath, 'UNCHANGED');
  const call = (name, args = {}) => client.callTool({ name, arguments: args });
  const first = await call('read_file', { path: filePath });
  assert.equal(JSON.parse(first.content[0].text).text, 'UNCHANGED');
  assert.equal(contexts(first).length, 1);
  const reminder = contexts(await call('read_file', { path: filePath }));
  assert.equal(reminder.length, 1, 'compact guidance reaches later chats sharing one OAuth client');
  assert.equal(reminder[0]._meta.compact, true, 'full descriptions are not repeated on every stateless request');
  assert.equal((await change({ name: 'write_file', enabled: false })).status, 200);
  const blocked = await call('write_file', { path: filePath, content: 'MUST_NOT_WRITE' });
  assert.equal(blocked.isError, true, 'cached tool call is checked against current policy');
  assert.match(blocked.content[0].text, /disabled/);
  assert.equal(contexts(blocked).length, 1, 'changed configuration is delivered on the next result');
  assert.equal(await readFile(filePath, 'utf8'), 'UNCHANGED');
  assert.ok(!(await client.listTools()).tools.some(tool => tool.name === 'write_file'));
  assert.equal((await settings()).tools.find(tool => tool.name === 'write_file').enabled, false, 'disabled tools remain configurable in dashboard');
  await change({ name: 'run_command', enabled: false });
  const remoteCommand = await call('run_on_device', { device_id: 'unpaired', command: 'Write-Output MUST_NOT_RUN' });
  assert.equal(remoteCommand.isError, true);
  assert.match(remoteCommand.content[0].text, /disabled/);
  assert.equal((await settings()).tools.find(tool => tool.name === 'run_on_device').blockedBy, 'run_command');
  await change({ name: 'windows_type', enabled: false });
  const nested = await call('windows_on_device', { device_id: 'unpaired', name: 'windows_type', arguments: { text: 'MUST_NOT_TYPE' } });
  assert.equal(nested.isError, true);
  assert.match(nested.content[0].text, /windows_type.*disabled/);
  const unknownNested = await call('windows_on_device', { device_id: 'unpaired', name: 'windows_unlisted_operation', arguments: {} });
  assert.equal(unknownNested.isError, true);
  assert.match(unknownNested.content[0].text, /unknown nested/);
  const skillDir = join(temporary, 'policy-proof-skill');
  await mkdir(skillDir);
  await writeFile(join(skillDir, 'SKILL.md'), '---\nname: policy-proof-skill\ndescription: Automatic context fixture\n---\n\nPRIVATE_FULL_MARKDOWN_NEVER_AUTOMATIC');
  const oldRevision = (await settings()).revision;
  assert.equal((await request('/admin/api/skills', { method: 'POST', headers, body: JSON.stringify({ folder: skillDir }) })).status, 200);
  const withSkill = await settings();
  assert.notEqual(withSkill.revision, oldRevision);
  assert.match(withSkill.prompt, /policy-proof-skill/);
  assert.doesNotMatch(withSkill.prompt, /PRIVATE_FULL_MARKDOWN|policy-proof-skill\\/);
  assert.equal(contexts(await call('read_file', { path: filePath })).length, 1, 'skill changes update existing client context');
  await change({ autoPrompt: false });
  assert.equal((await settings()).prompt, '');
  assert.equal(contexts(await call('read_file', { path: filePath })).length, 0, 'automatic context off is enforced on results');
  await client.close(); client = await connect();
  assert.doesNotMatch(client.getInstructions(), /selected context|policy-proof-skill/);
  await change({ name: 'write_file', enabled: true });
  assert.ok(!(await call('write_file', { path: filePath, content: 'RESTORED' })).isError);
  await client.close(); client = undefined;
  await gateway.close();
  gateway = await startGateway({ port, publicUrl: origin, configDir, connectionSecret: secret });
  client = await connect();
  assert.equal((await settings()).autoPrompt, false, 'automatic context preference survives restart');
  assert.ok(!(await client.listTools()).tools.some(tool => tool.name === 'run_command'), 'tool toggle survives restart');
  assert.ok((await client.listTools()).tools.some(tool => tool.name === 'write_file'), 'reenabled tool survives restart');
  await writeFile(join(temporary, 'tool-policy.json'), '{broken permissions');
  assert.equal((await client.listTools()).tools.length, 0);
  assert.equal((await call('read_file', { path: filePath })).isError, true);
  assert.ok((await settings()).tools.every(tool => !tool.enabled));
  assert.equal((await request('/admin/api/requests')).status, 200, 'admin diagnostics remain available when all tools are disabled');
  assert.equal((await (await request('/admin/api/requests')).json()).runtime.desktop.state, 'disabled');
  await change({ group: 'files', enabled: true });
  assert.ok(!(await call('read_file', { path: filePath })).isError);
  assert.equal((await settings()).tools.find(tool => tool.name === 'run_command').enabled, false, 'recovery does not reenable other groups');
  await client.close(); client = undefined;
  await gateway.close();
  gateway = await startGateway({ port, publicUrl: 'https://policy-public.example', configDir, connectionSecret: secret });
  assert.equal((await request('/admin/api/tools', { headers: { Host: 'policy-public.example' } })).status, 404, 'public tunnel host cannot read private tool controls');
  assert.equal((await request('/admin/api/tools', { method: 'POST', headers: { ...headers, Host: 'policy-public.example' }, body: JSON.stringify({ group: 'commands', enabled: true }) })).status, 404, 'public tunnel host cannot change private tool controls');
  console.log('PASS: persisted tool/group controls, stale calls, remote alias/nested rejection, failclosed corruption, private admin/CSRF and refreshed MCP context.');
} finally {
  await client?.close().catch(() => {});
  await gateway?.close();
  assert.ok(resolve(temporary).startsWith(resolve(tmpdir()) + sep));
  await rm(temporary, { recursive: true, force: true, maxRetries: 5, retryDelay: 150 });
}
